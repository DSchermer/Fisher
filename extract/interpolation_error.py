"""Measure how far interpolation between catalog openings can be from the catalog's own values.

Leave-one-out on every Cv curve: hide an interior point, interpolate it from the remaining points, compare
with the printed value. Because the hidden point's neighbours are twice the printed spacing apart, this
overstates the error of interpolating at the printed spacing (curvature error grows with the square of the
spacing, so roughly 4x). Writes docs/INTERPOLATION.md.

Usage:
    python extract/interpolation_error.py docs/INTERPOLATION.md
"""
from __future__ import annotations

import math
import statistics
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from fisher import Catalog  # noqa: E402
from fisher.catalog import pchip  # noqa: E402

METHODS = ("linear", "log-linear", "pchip")


def estimates(pts, i):
    (x0, y0), (x1, _), (x2, y2) = pts[i - 1], pts[i], pts[i + 1]
    t = (x1 - x0) / (x2 - x0)
    rest = [p for j, p in enumerate(pts) if j != i]
    return {"linear": y0 + (y2 - y0) * t,
            "log-linear": math.exp(math.log(y0) + (math.log(y2) - math.log(y0)) * t),
            "pchip": pchip([p[0] for p in rest], [p[1] for p in rest], x1)}


def main(out_path: str) -> None:
    cat = Catalog.load()
    errs: dict[tuple, dict[str, list]] = defaultdict(lambda: defaultdict(list))
    for c in cat.configs.values():
        pts = [p for p in c.curve("Cv") if p[1] > 0]
        if len(pts) < 5:
            continue
        char = (c.characteristic or "not stated").lower()
        char = next((k for k in ("modified", "equal", "linear", "quick") if k in char), "not stated")
        top = pts[-1][0]
        for i in range(1, len(pts) - 1):
            x1, y1 = pts[i]
            band = "low (<35%)" if x1 / top < 0.35 else "mid" if x1 / top < 0.75 else "high (>=75%)"
            for m, v in estimates(pts, i).items():
                e = abs(v - y1) / y1 * 100
                errs[(c.motion, char, "all")][m].append(e)
                errs[(c.motion, char, band)][m].append(e)
    lines = ["# Interpolation between catalog openings", "",
             "Generated by `extract/interpolation_error.py`. Each interior Cv point of every curve was hidden and "
             "re-estimated from the others; the table gives the absolute error as a percent of the printed value. "
             "The hidden point's neighbours are twice the printed spacing apart, so these errors overstate "
             "interpolation at the printed spacing (roughly by 4x, since the error from curvature grows with the "
             "square of the spacing).", "",
             "`Config.value_at(..., interp='pchip')` and `opening_for(..., interp='pchip')` use the monotone cubic. "
             "The default stays linear until an engineer chooses (docs/MORNING.md).", "",
             "| motion | characteristic | opening | points | linear median / p95 | log-linear median / p95 | "
             "pchip median / p95 |", "|---|---|---|---|---|---|---|"]
    for k in sorted(errs, key=lambda k: (k[0], k[1], k[2] != "all", k[2])):
        n = len(errs[k]["linear"])
        if n < 100:
            continue
        cells = []
        for m in METHODS:
            v = sorted(errs[k][m])
            cells.append(f"{statistics.median(v):.1f}% / {v[int(0.95 * len(v))]:.1f}%")
        lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {n} | " + " | ".join(cells) + " |")
    best = sum(1 for k in errs if len(errs[k]["linear"]) >= 100 and
               statistics.median(errs[k]["pchip"]) <= min(statistics.median(errs[k][m]) for m in METHODS))
    total = sum(1 for k in errs if len(errs[k]["linear"]) >= 100)
    lines += ["", f"Reading it: pchip has the smallest median error in {best} of {total} groups; log-linear helps "
              "equal-percentage curves but hurts linear ones; every method's largest errors are at low openings, "
              "where the printed curves bend most."]
    Path(out_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:])
